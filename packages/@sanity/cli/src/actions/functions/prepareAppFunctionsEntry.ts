import {mkdir, writeFile} from 'node:fs/promises'
import path from 'node:path'

import {isStaging} from '@sanity/cli-core/util'

import {readAppFunctionState} from './appFunctionState.js'

/** Wrap the app entry with its function binding without changing user source. */
export async function prepareAppFunctionsEntry({
  appId,
  entry,
  organizationId,
  stackId,
  workDir,
}: {
  appId?: string
  entry: string | undefined
  organizationId: string | undefined
  stackId?: string
  workDir: string
}): Promise<string | undefined> {
  if (!entry || !organizationId) return entry
  if (!stackId) {
    const saved = await readAppFunctionState(workDir)
    if (
      saved?.organizationId !== organizationId ||
      saved.environment !== (isStaging() ? 'staging' : 'production') ||
      (appId && saved.appId !== appId)
    ) {
      return entry
    }
    stackId = saved.stackId
  }
  if (!stackId) return entry

  // Both standalone and federation runtimes can import this sibling entry.
  const directory = path.join(workDir, '.sanity')
  const file = path.join(directory, 'app-functions-entry.js')
  const relativeEntry = path.relative(directory, path.resolve(workDir, entry)).replaceAll('\\', '/')
  const importPath = relativeEntry.startsWith('.') ? relativeEntry : `./${relativeEntry}`
  const binding = JSON.stringify({organizationId, stackId})
  await mkdir(directory, {recursive: true})
  await writeFile(
    file,
    `// Generated by Sanity CLI. Changes are overwritten.\nimport {createElement} from 'react'\nimport {AppFunctionsProvider} from '@sanity/sdk-react'\nimport {functionContracts} from './function-contracts.js'\nimport App from ${JSON.stringify(importPath)}\n\nconst binding = {...${binding}, functions: functionContracts}\n\nexport default function AppWithFunctions(props) {\n  return createElement(AppFunctionsProvider, {value: binding}, createElement(App, props))\n}\n`,
  )
  return file
}
