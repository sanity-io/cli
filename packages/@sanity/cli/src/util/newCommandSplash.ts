import {styleText} from 'node:util'

type LogFn = (message?: string) => void

const ART = [
  '          -          #:      @@@@',
  '         @@@      @@@@@    -@@@=   @@@',
  '       @@@@   %@@@@@@.    @@@@ %@@@@@@',
  '      @@@% @@@@@@@#     %@@@@@@@@@-',
  '    @@@@@@@@@@@@@      @@@@@@@@.',
  '   @@@@@@@= @@@#     @@@@@@@        @@@@@',
  '   @@@@   @@@@    @@@@@@         @@@@@@@',
  '         @@@@ @@@@@@@@        @@@@@@@@',
  '       +@@@@@@@@@@@@@      @@@@@@@@@@',
  '      @@@@@@@@ @@@@     @@@@@@ @@@@',
  '     @@@@@%  *@@@%  .@@@@@%  .@@@@ .@@@@',
  '      .-    @@@@ .@@@@@%    #@@@.@@@@@@@@',
  '          *@@@@@@@@@%      @@@@@@@@#@@@@',
  '         @@@@@@@@        #@@@@@@#  @@@@',
  '       @@@@@@@           @@@@#    @@@@',
  '      #@@@@               *      @@@+',
  '                                  =',
]

export function renderNewCommandSplash(log: LogFn): void {
  log('')
  for (const line of ART) log(styleText('cyan', line))
  log('')
}
