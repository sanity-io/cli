const knownRoots = new Set([...commandPaths].map((path) => path.split(' ')[0]))

export function commandIdentity(group: unknown, args: unknown) {
  const root = typeof group === 'string' ? group.split(':') : []
  const parts = [...root, ...(Array.isArray(args) ? args : [])]
  if (!knownRoots.has(root[0])) return {commandArguments: [], groupOrCommand: 'unknown'}

  let commandArguments: string[] = []
  for (let length = 2; length <= Math.min(parts.length, 4); length++) {
    const candidate = parts.slice(0, length)
    if (!candidate.every((part) => typeof part === 'string')) break
    if (commandPaths.has(candidate.join(' '))) commandArguments = candidate.slice(1)
  }
  return {commandArguments, groupOrCommand: root[0]}
}
